// Generates src/generated/ from schema/: the TypeScript types (json-schema-to-typescript) and precompiled validators
// (Ajv standalone, ESM), so the tool runtime ships no schema compiler and nothing is written twice by hand.
//   node scripts/generate.mjs           write the files
//   node scripts/generate.mjs --check   exit 1 when a committed file differs (test/generated.test.ts runs this too)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { compile } from "json-schema-to-typescript";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneModule from "ajv/dist/standalone/index.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "generated");
const BANNER = "// GENERATED by scripts/generate.mjs from schema/*.schema.json. Do not edit; run `npm run generate`.\n";
const SCHEMAS = {
  manifest: { file: "manifest.schema.json", validator: "validateManifest" },
  envelope: { file: "envelope.schema.json", validator: "validateMessage" },
};

const read = (file) => JSON.parse(readFileSync(join(ROOT, "schema", file), "utf8"));

/** The schema without its prose: the validators don't need it, and it is most of their size. */
function bare(node) {
  if (Array.isArray(node)) return node.map(bare);
  if (node === null || typeof node !== "object") return node;
  return Object.fromEntries(Object.entries(node).filter(([k]) => k !== "description" && k !== "title" || false).map(([k, v]) => [k, bare(v)]));
}

// Ajv's standalone code reaches for two runtime helpers with require(), which an ES module in a browser can't do:
// they are defined here instead, for JSON values (what crosses the wire).
const HELPERS = `
function equal(a, b) {
  if (a === b) return true;
  if (typeof a !== "object" || typeof b !== "object" || a === null || b === null) return a !== a && b !== b;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  const ka = Object.keys(a), kb = Object.keys(b);
  if (ka.length !== kb.length) return false;
  for (const k of ka) if (!Object.prototype.hasOwnProperty.call(b, k) || !equal(a[k], b[k])) return false;
  return true;
}
function ucs2length(str) { let n = 0; for (const _ of str) n++; return n; }
`;

// The envelope's top-level `type` is there for Ajv's discriminator only; in the types it would intersect every message
// with an index signature, and no message could be built as itself.
// A property's own `title` (the server's model writes one on each) would name a type alias per field (Url1, Sdk1); only
// the root's and the $defs' titles name types.
function forTypes(schema) {
  const untitled = (node, keep) => {
    if (Array.isArray(node)) return node.map((n) => untitled(n, false));
    if (!node || typeof node !== "object") return node;
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === "title" && !keep) continue;
      out[k] = k === "$defs" ? Object.fromEntries(Object.entries(v).map(([n, d]) => [n, untitled(d, true)])) : untitled(v, false);
    }
    return out;
  };
  const typed = untitled(schema, true);
  if (!typed.oneOf) return typed;
  const { properties: _p, required: _r, type: _t, ...rest } = typed;
  return rest;
}

export async function generate() {
  const files = {};
  for (const [name, { file }] of Object.entries(SCHEMAS)) {
    const ts = await compile(forTypes(read(file)), name === "manifest" ? "ToolManifest" : "ToolMessage", {
      bannerComment: BANNER.trimEnd(), additionalProperties: true, unreachableDefinitions: true, format: true, style: { printWidth: 120 },
    });
    files[`${name}.ts`] = ts;
  }
  const ajv = new Ajv2020({ code: { source: true, esm: true, lines: false }, discriminator: true, strict: true, allErrors: true });
  const ids = {};
  for (const { file, validator } of Object.values(SCHEMAS)) {
    const schema = bare(read(file));
    ajv.addSchema(schema);
    ids[validator] = schema.$id;
  }
  const standalone = standaloneModule.default ?? standaloneModule;
  let code = standalone(ajv, ids);
  code = code.replace(/require\("ajv\/dist\/runtime\/equal"\)\.default/g, "equal").replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, "ucs2length");
  if (/require\(/.test(code)) throw new Error("the standalone validators still require() something: " + code.match(/require\([^)]*\)/)[0]);
  code = code.replace(/^"use strict";/, "");
  files["validators.js"] = `${BANNER}/* eslint-disable */\n${HELPERS}\n${code}\n`;
  files["validators.d.ts"] = `${BANNER}export interface ValidationError { instancePath: string; schemaPath: string; keyword: string; params: Record<string, unknown>; message?: string }
export interface Validator { (data: unknown): boolean; errors?: ValidationError[] | null }
export declare const validateManifest: Validator;
export declare const validateMessage: Validator;
`;
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = await generate();
  const check = process.argv.includes("--check");
  const stale = [];
  mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(files)) {
    const path = join(OUT, name);
    let have = null;
    try { have = readFileSync(path, "utf8"); } catch { /* none yet */ }
    if (have === text) continue;
    stale.push(name);
    if (!check) writeFileSync(path, text);
  }
  if (check && stale.length) { console.error(`stale: ${stale.join(", ")} (run npm run generate)`); process.exit(1); }
  console.error(stale.length ? `${check ? "stale" : "written"}: ${stale.join(", ")}` : "src/generated is current");
}
